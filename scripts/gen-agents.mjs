#!/usr/bin/env node
// ==============================================================================
// gen-agents.mjs — Generates agents/<role>.md from skills/crew/<role>/SKILL.md
//
// WHY: the `model:` in a SKILL.md only applies when the skill is invoked as a
// skill (e.g. `/keymaker`). A subagent launched with the `Agent` tool and
// `subagent_type: "general-purpose"` ignores it and inherits the caller's model.
// A real subagent definition (agents/<role>.md) carries its own `model:` and
// preloads the skill via `skills:`, so dispatching `subagent_type: "<role>"`
// always runs on the model declared in the skill.
//
// SINGLE SOURCE OF TRUTH: the SKILL.md frontmatter (`name`, `model`, bracketed
// tagline in `description`). Never edit agents/*.md by hand; re-run this script.
//
// Usage: node scripts/gen-agents.mjs [--check]
//   --check   exit 1 if any agents/*.md is missing or out of date (CI-friendly)
// ==============================================================================
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, unlinkSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CREW = join(ROOT, "skills", "crew");
const OUT = join(ROOT, "agents");

// Roles that are NOT dispatched as subagents:
//  - morpheus: the orchestrator itself (runs in the main thread)
//  - hardline: session-close flow, interacts with Neo directly
//  - neb:      read-only live console for Neo
// (The Source lives in skills/source and is outside the crew by design.)
const EXCLUDE = new Set(["morpheus", "hardline", "neb"]);
const MODELS = new Set(["haiku", "sonnet", "opus"]);

const check = process.argv.includes("--check");

function frontmatter(text, file) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) throw new Error(`No frontmatter in ${file}`);
  const get = (key) => {
    const line = m[1].split(/\r?\n/).find((l) => l.startsWith(`${key}:`));
    if (!line) return null;
    return line.slice(key.length + 1).trim().replace(/^"(.*)"$/s, "$1");
  };
  return { name: get("name"), model: get("model"), description: get("description") };
}

function render({ name, model, tagline }) {
  const title = name.charAt(0).toUpperCase() + name.slice(1);
  return `---
name: ${name}
description: "${tagline} Subagent wrapper of the /${name} skill (model: ${model}). Dispatch ONLY from Morpheus or another crew role via the Agent tool; Neo invokes /${name} directly as a skill."
model: ${model}
skills:
  - ${name}
---
<!-- GENERATED by scripts/gen-agents.mjs from skills/crew/${name}/SKILL.md — DO NOT EDIT BY HAND. -->

# ${title} — subagent wrapper

You are executing the \`/${name}\` role as an **isolated subagent** dispatched by Morpheus or another crew role.

1. Your full \`/${name}\` skill is preloaded in your context. If you cannot see it, read \`~/.claude/skills/${name}/SKILL.md\` first, before any other action.
2. Execute exactly the mission in the dispatch prompt, obeying that skill's reading order, guardrails, prohibitions and the project's \`CLAUDE.md\`.
3. You are not talking to Neo: do not ask for permission or yield the prompt. Finish the mission and return your report in the canonical envelope (\`FROM / TO / STATUS / DETAILS / RECOMMENDED NEXT STEP\`); your dispatcher reads it and decides the next step.
4. Your model is fixed by this agent definition. Never request \`/model\` switches; if the mission exceeds your tier, say so in \`RECOMMENDED NEXT STEP\`.
5. To involve another crew role, dispatch it with the \`Agent\` tool (\`subagent_type: "<role>"\`) — never the \`Skill\` tool — and respect \`MAX_HOPS = 2\`.
`;
}

const roles = readdirSync(CREW, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !EXCLUDE.has(d.name))
  .map((d) => d.name)
  .sort();

mkdirSync(OUT, { recursive: true });
let stale = 0;
const expected = new Set();

for (const role of roles) {
  const file = join(CREW, role, "SKILL.md");
  const fm = frontmatter(readFileSync(file, "utf8"), file);
  if (fm.name !== role) throw new Error(`${file}: frontmatter name "${fm.name}" != folder "${role}"`);
  if (!MODELS.has(fm.model)) throw new Error(`${file}: model "${fm.model}" must be one of ${[...MODELS].join(", ")}`);
  const tag = (fm.description || "").match(/^\[[^\]]+\]/);
  const tagline = tag ? tag[0] : `[${role}]`;
  const content = render({ name: role, model: fm.model, tagline });
  const out = join(OUT, `${role}.md`);
  expected.add(`${role}.md`);
  const current = existsSync(out) ? readFileSync(out, "utf8") : null;
  if (current !== content) {
    stale++;
    if (!check) writeFileSync(out, content);
    console.log(`${check ? "STALE " : "wrote "} agents/${role}.md  (model: ${fm.model})`);
  }
}

// Remove orphan agent files (role deleted or newly excluded)
for (const f of readdirSync(OUT)) {
  if (f.endsWith(".md") && !expected.has(f)) {
    stale++;
    if (!check) unlinkSync(join(OUT, f));
    console.log(`${check ? "ORPHAN" : "removed"} agents/${f}`);
  }
}

console.log(`${roles.length} agents ${stale ? (check ? `— ${stale} out of date` : `— ${stale} updated`) : "— all up to date"}`);
if (check && stale) process.exit(1);
